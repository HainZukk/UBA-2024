#Crear una secuencia con numero distintos , y luego devolver el elemento maximo y minimo 


secuencia = [7,2,3,5,6]
#Utilizamos max para saber el maximo 
maximo = max(secuencia)
#Utilizamos min para saber el minimo 
minimo = min(secuencia)

print("El maximo de la secuencia es  : " , maximo)
print("El minimo de la secuencia es  : " , minimo)