#Crear tuplas con datos correspondientes 

tupla1=("Tobias" , 18)
tupla2=("Liz" , 17)
tupla3=("Dino" , 22)

lista_de_tuplas = [tupla1,tupla2,tupla3]
print("Lista de tuplas : " , lista_de_tuplas)


# 1. Organización y estructura de datos: Almacenar las tuplas relacionadas en una lista proporciona una estructura de datos más organizada y coherente. 
        #Puedes acceder a todas las tuplas relacionadas como un solo objeto, lo que facilita la 
            #manipulación y el procesamiento de los datos.

# 2. Facilidad de acceso y manipulación: Al tener las tuplas en una lista, puedes acceder a cada una de ellas utilizando índices. Esto facilita la recuperación 
        #de datos específicos y la realización de operaciones en las tuplas, como modificar valores o agregar nuevas tuplas.

# 3.teración y procesamiento: Con una lista de tuplas, puedes iterar fácilmente sobre todas las tuplas utilizando bucles, lo que simplifica las operaciones que involucran 
    #todas las tuplas, como imprimir o realizar cálculos en base a los datos de cada tupla.