nombre = "liz"
apellido = "peralta"

# Conocer el largo de un string (Cadena de caracteres)
largo_nombre = len(nombre)
print(largo_nombre)
largo_apellido = len(apellido)
print(largo_apellido)
# Concatenar 2 strings
nombre_materia = nombre +" "+apellido    # Para generar un espacio tenemos que poner " " para generar el espacio entre los strings
print(nombre_materia)
# Cortar un string
apellido_corto = apellido[2:6:2]
print(apellido_corto)

